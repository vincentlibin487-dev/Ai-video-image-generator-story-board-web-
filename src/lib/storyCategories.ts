export const STORY_CATEGORIES: StoryCategory[] = (
  Object.entries(RAW_GROUPS) as [StoryCategoryGroupId, RawCategorySeed[]][]
).flatMap(([groupId, items]) =>
  items.map((item) => ({
    id: item.id,
    groupId,
    name: item.name,
    tone: item.tone,
    visualStyle: item.visual,
    cameraFocus: item.camera,
    pacing: item.pacing,
    dialogueStyle: item.dialogue,
    bgmVibe: item.bgm,
    settingCue: item.setting,
  }))
);

export function getCategoryById(id?: string | null): StoryCategory | undefined {
  if (!id || id === 'all') return undefined;
  return STORY_CATEGORIES.find((c) => c.id === id);
}

export function getCategoryGroup(groupId: StoryCategoryGroupId): StoryCategoryGroup {
  return STORY_CATEGORY_GROUPS.find((g) => g.id === groupId) || STORY_CATEGORY_GROUPS[0];
}

export function searchStoryCategories(
  query: string,
  groupId: StoryCategoryGroupId | 'all' = 'all'
): StoryCategory[] {
  const q = query.trim().toLowerCase();
  return STORY_CATEGORIES.filter((cat) => {
    if (groupId !== 'all' && cat.groupId !== groupId) return false;
    if (!q) return true;
    const grp = getCategoryGroup(cat.groupId);
    return (
      cat.name.toLowerCase().includes(q) ||
      cat.tone.toLowerCase().includes(q) ||
      cat.settingCue.toLowerCase().includes(q) ||
      cat.visualStyle.toLowerCase().includes(q) ||
      grp.labels.en.toLowerCase().includes(q) ||
      grp.labels.ml.toLowerCase().includes(q)
    );
  });
}
